def generate_city_venues(city: str,
                         api_key: str = None,
                         anthropic_key: str = None,
                         model: str = "deepseek-chat",
                         planning_model: str = None,
                         db_path: Path = None,
                         dry_run: bool = False,
                         workers: int = 5,
                         verbose: bool = False,
                         limit: int = None,
                         wrong_info_only: bool = False,
                         window_id: str = None,
                         ors_key: str = None,
                         skip_matrix: bool = False,
                         skip_tickets: bool = False,
                         skip_venue_difficulty: bool = False) -> dict:
    """
    Full orchestration: research city -> plan venues -> generate all -> validate.

    Events are generated per seasonal window:
    - If window_id is given: generate events for that specific window only.
    - If window_id is None (default): generate events for ALL windows of the city.
      The venue pool is generated once and shared; events are window-specific.

    Returns summary dict with counts, issues, and events_written count.
    """
    if db_path is None:
        db_path = get_city_db_path(city)
    print(f"\n🏙  Generating venue pool for {city.title()}...")

    # ── Step 1: Ensure city config exists ────────────────────────────────────
    print("\n[1/4] City config...")
    # research_city uses DeepSeek (OpenAI-compatible), always deepseek-chat
    # plan_venues uses Anthropic; --planning-model controls that model
    _research_model  = "deepseek-chat"
    _planning_model  = planning_model or "claude-sonnet-4-6"
    city_config = research_city(
        city_name=city, api_key=api_key, model=_research_model,
        db_path=db_path, dry_run=dry_run
    )

    city_key = city.lower().replace(" ", "_")
    conn = get_connection(db_path)
    db_row = conn.execute(
        "SELECT * FROM city_config WHERE city = ?", (city_key,)
    ).fetchone()
    conn.close()
    if db_row:
        city_config = dict(db_row)
        # Unpack JSON columns
        for col in ("districts", "cuisine_variety", "task_dates"):
            if isinstance(city_config.get(col), str):
                city_config[col] = json.loads(city_config[col] or "[]")

    # Backfill from stub if any list fields are empty (older DB rows)
    if city_key in STUB_CONFIGS:
        stub = STUB_CONFIGS[city_key]
        if not city_config.get("districts"):
            city_config["districts"] = stub.get("districts", [])
        if not city_config.get("cuisine_variety"):
            city_config["cuisine_variety"] = stub.get("cuisine_variety", [])

    # ── Step 2: Ensure windows exist ─────────────────────────────────────────
    # For known cities (london/hokkaido/rio): populate_windows writes hardcoded defs.
    # For new cities: generate_and_store_windows calls LLM. Skip if already populated.
    from scripts.generation.populate_seasonal_windows import (
        populate_windows as _pop_windows,
        get_windows as _get_windows,
        generate_and_store_windows as _gen_windows,
    )
    _existing_windows = _get_windows(city_key, db_path=db_path)
    if not _existing_windows:
        print(f"\n[2/5] Window generation...")
        _pop_result = _pop_windows(city_key, db_path=db_path)
        if _pop_result["status"] == "unknown_city":
            if not dry_run:
                # Live run: use LLM (falls back to stub if no key or LLM fails)
                _gen_result = _gen_windows(
                    city_key, city_config,
                    api_key=anthropic_key,
                    model=_planning_model,
                    db_path=db_path,
                )
                if _gen_result["status"] in ("ok", "stub"):
                    label = "" if _gen_result["status"] == "ok" else " (stub fallback)"
                    print(f"  [x] {_gen_result['windows_written']} windows generated{label}")
                else:
                    print(f"  ⚠ Window generation failed: {_gen_result.get('message','')}")
            else:
                # Dry-run: always write stub windows so downstream steps can proceed
                from scripts.generation.populate_seasonal_windows import _stub_windows as _sw
                _stub_wins = _sw(city_key, city_config)
                _conn_w = get_connection(db_path)
                _conn_w.execute(
                    "UPDATE city_config SET seasonal_windows = ? WHERE city = ?",
                    (json.dumps(_stub_wins), city_key)
                )
                _conn_w.commit()
                _conn_w.close()
                print(f"  [x] {len(_stub_wins)} stub windows written (dry-run)")
        elif _pop_result["status"] == "ok":
            print(f"  [x] {_pop_result['windows_written']} hardcoded windows loaded")
    else:
        print(f"\n[2/5] Windows: {len(_existing_windows)} already in DB - skipping")

    # ── Step 3: Plan venue mix ────────────────────────────────────────────────
    # Reload windows after Step 2 (may have just been generated)
    _all_windows = _get_windows(city_key, db_path=db_path) or []
    if window_id:
        _windows_to_process = [w for w in _all_windows if w["window_id"] == window_id]
        if not _windows_to_process:
            print(f"  ⚠ Window '{window_id}' not found in DB - running without events")
    else:
        _windows_to_process = _all_windows

    # Generate city interests BEFORE plan_venues so the planning prompt
    # has cultural context (visitor_interests) for venue selection.
    city_interests = generate_city_interests(city_config, api_key=anthropic_key, model=_planning_model)

    # Plan venues using first window for seasonal context (or no context if no windows)
    _planning_window = _windows_to_process[0] if _windows_to_process else None
    print(f"\n[3/5] Planning venue mix{' (window: ' + _planning_window['label'] + ')' if _planning_window else ''}...")
    briefs, _ = plan_venues(
        city_config=city_config,
        api_key=anthropic_key,
        model=_planning_model,
        dry_run=dry_run,
        window=_planning_window,
        n_venues=limit or 50,
    )

    # ── Post-process briefs: enforce pace and wrong_info by code ─────────────
    #
    # Pace: Design decision says agent uses category + booking_required +
    # recommended_visit_minutes as signals - editorial judgment, not mechanical.
    # However DeepSeek defaults everything to "moderate", so if no spread
    # is present we assign by code using the same signals at brief time.
    # (booking_required/visit_minutes aren't in briefs yet, so we use
    #  category + traffic_tier as proxies, matching the design intent.)
    #
    # Category-based pace logic (mirrors DESIGN_DECISIONS.md guidance):
    #   intense: major museums, ticketed attractions (high-traffic sights)
    #   relaxed: parks, neighbourhood walks, cafes (low-pressure venues)
    #   moderate: everything else (restaurants, bars, galleries, mid museums)

    PACE_INTENSE_CATS  = {"museum", "attraction"}
    PACE_RELAXED_CATS  = {"park", "neighbourhood", "cafe"}

    # Score each brief: intense beats relaxed; high-traffic museums = intense
    def _brief_pace(b: dict) -> str:
        cat  = b.get("category", "")
        tier = b.get("traffic_tier", "mid")
        if cat in PACE_INTENSE_CATS:
            return "intense"
        if cat in PACE_RELAXED_CATS:
            return "relaxed"
        # Bars at high-traffic = moderate-intense; restaurants = moderate
        if cat == "bar" and tier == "high":
            return "intense"
        return "moderate"

    pace_counts = {"relaxed": 0, "moderate": 0, "intense": 0}
    for b in briefs:
        p = b.get("recommended_pace")
        if p in pace_counts:
            pace_counts[p] += 1

    # Only override if LLM produced no spread (all moderate)
    all_moderate = pace_counts["relaxed"] == 0 and pace_counts["intense"] == 0
    if all_moderate:
        print("  ⚠ All briefs are 'moderate' - assigning pace from category+tier (design signals)")
        for b in briefs:
            if b.get("recommended_pace") not in ("relaxed", "intense"):
                b["recommended_pace"] = _brief_pace(b)
    else:
        # LLM assigned some spread - fill any nulls with category-based default
        for b in briefs:
            if b.get("recommended_pace") not in ("relaxed", "moderate", "intense"):
                b["recommended_pace"] = _brief_pace(b)

    # Wrong info: if LLM assigned fewer than _n_wi, assign by code from mid/low pool
    import random as _random
    _n_wi_target = max(2, round(len(briefs) * 0.40))  # W1: raised from 0.24
    _wi_actual   = sum(1 for b in briefs if b.get("has_wrong_info"))
    if _wi_actual < _n_wi_target:
        print(f"  ⚠ Only {_wi_actual}/{_n_wi_target} wrong_info briefs - assigning remainder by code")
        mid_low_unset = [b for b in briefs
                         if not b.get("has_wrong_info")
                         and b.get("traffic_tier") in ("mid", "low")]
        _random.shuffle(mid_low_unset)
        for b in mid_low_unset[:_n_wi_target - _wi_actual]:
            b["has_wrong_info"] = True

    # ── P2: Tier rebalancing - same pattern as wrong_info ────────────────────
    # LLM systematically skews high/mid; enforce low-tier target by code.
    from collections import Counter as _Counter
    _n_venues_actual = len(briefs)
    _n_high_tgt = max(3, round(_n_venues_actual * 0.26))
    _n_mid_tgt  = max(5, round(_n_venues_actual * 0.42))
    _n_low_tgt  = _n_venues_actual - _n_high_tgt - _n_mid_tgt
    _tier_actual = _Counter(b.get("traffic_tier", "mid") for b in briefs)
    _low_deficit = _n_low_tgt - _tier_actual.get("low", 0)
    if _low_deficit > 0:
        print(f"  ⚠ Only {_tier_actual.get('low',0)}/{_n_low_tgt} low-tier - downgrading {_low_deficit} mid venues")
        mid_candidates = sorted(
            [b for b in briefs if b.get("traffic_tier") == "mid"],
            key=lambda b: len(b.get("name", ""))
        )
        for b in mid_candidates[:_low_deficit]:
            b["traffic_tier"] = "low"

    # Print brief summary
    from collections import Counter
    cat_counts  = Counter(b["category"]         for b in briefs)
    tier_counts = Counter(b["traffic_tier"]      for b in briefs)
    pace_dist   = Counter(b.get("recommended_pace", "?") for b in briefs)
    wi_count    = sum(1 for b in briefs if b.get("has_wrong_info"))
    print(f"  Categories: {dict(cat_counts)}")
    print(f"  Tiers: {dict(tier_counts)}")
    print(f"  Pace: {dict(pace_dist)}")
    print(f"  Wrong info planned: {wi_count}")

    # ── Step 3b: Enrich with Overpass data ───────────────────────────────────
    print("\n[3b/5] Enriching with Overpass (real venue coordinates)...")
    briefs = enrich_briefs(briefs, city_config, dry_run=dry_run)

    if wrong_info_only:
        original_count = len(briefs)
        briefs = [b for b in briefs if b.get("has_wrong_info") and b.get("traffic_tier") in ("mid", "low")]
        print(f"  ⚠ --wrong-info-only: {len(briefs)} of {original_count} briefs have wrong info (mid/low tier)")

    if limit is not None and len(briefs) > limit:
        # Tier-aware selection in plan_venues already handled trimming.
        # Only warn — don't re-truncate, as that would squeeze out low-tier venues.
        n_high = sum(1 for b in briefs if b.get("traffic_tier") == "high")
        print(f"  ℹ {len(briefs)} briefs after tier-aware selection "
              f"(requested {limit}, {n_high} high-traffic kept)")

    # ── Step 4: Generate events for all windows ───────────────────────────────
    # Runs BEFORE venue agents so each venue receives its assigned events.
    # city_interests already generated before plan_venues (Step 3).
    all_events: list[dict] = []

    if _windows_to_process and not dry_run and anthropic_key:
        print(f"\n[4/5] Generating events for {len(_windows_to_process)} window(s)...")
        all_events = generate_events_for_windows(
            city_config=city_config,
            windows=_windows_to_process,
            venue_briefs=briefs,
            city_interests=city_interests,
            api_key=anthropic_key,
            model=_planning_model,
        )
    elif _windows_to_process:
        print("\n[4/5] Skipping event generation (dry-run or no API key)")
    else:
        print("\n[4/5] No windows - skipping event generation")

    # Build events_by_venue: venue_index -> [event, ...] for venue agent injection
    events_by_venue: dict[int, list[dict]] = {}
    for ev in all_events:
        idx = ev.get("venue_index")
        if isinstance(idx, int):
            events_by_venue.setdefault(idx, []).append(ev)

    # Attach event_briefs to each brief before parallel dispatch
    for i, brief in enumerate(briefs):
        brief["event_briefs"] = events_by_venue.get(i, [])

    # ── Step 5: Generate all venues — two-phase with regulation steering ─────
    total = len(briefs)
    PHASE1_SIZE = min(total // 2, 25)  # first half, capped at 25
    phase1_briefs = briefs[:PHASE1_SIZE]
    phase2_briefs = briefs[PHASE1_SIZE:]

    print(f"\n[5/5] Generating {total} venues ({workers} parallel workers)")
    print(f"  Phase 1: {len(phase1_briefs)} venues (no regulation steering)")
    print(f"  Phase 2: {len(phase2_briefs)} venues (with regulation steering if needed)")
    print(f"  Logs -> logs/venue_runs/")
    successes = []
    failures = []

    def _progress_line():
        done = len(successes) + len(failures)
        pct = done / total * 100
        bar_len = 30
        filled = int(bar_len * done / total)
        bar = "█" * filled + "░" * (bar_len - filled)
        fail_str = f"  {len(failures)} failed" if failures else ""
        print(f"\r  [{bar}] {done:2d}/{total} ({pct:5.1f}%){fail_str}", end="", flush=True)

    def _run_batch(batch):
        """Run a batch of briefs in parallel, append to successes/failures."""
        _progress_line()
        with ThreadPoolExecutor(max_workers=workers) as executor:
            futures = {
                executor.submit(
                    _generate_one, brief, city_key, api_key, model, db_path, verbose
                ): brief
                for brief in batch
            }
            for future in as_completed(futures):
                brief = futures[future]
                try:
                    result = future.result()
                    if result["status"] == "success":
                        successes.append(result)
                    else:
                        failures.append({"brief_name": brief["name"], **result})
                except Exception as e:
                    failures.append({"brief_name": brief["name"], "error": str(e)})
                _progress_line()

    # ── Phase 1: generate first batch without steering ────────────────────────
    _run_batch(phase1_briefs)

    # ── Checkpoint: compute regulation distribution from DB ───────────────────
    _REG_STEERING_FIELDS = [
        "wheelchair_accessible", "pet_friendly", "photography_allowed",
        "family_friendly", "reservation_required", "outside_food_allowed",
    ]
    _SKEW_THRESHOLD = 0.75  # if >75% on one side, steer toward minority

    reg_directives_for_phase2 = {}
    if phase2_briefs and not dry_run:
        try:
            _conn = get_connection(db_path)
            _verified = _conn.execute(
                "SELECT * FROM venues WHERE city=? AND page_status='verified'",
                (city_key,)
            ).fetchall()
            _conn.close()

            if len(_verified) >= 10:  # need enough data for meaningful distribution
                print(f"\n  [regulation checkpoint] {len(_verified)} venues committed")
                for reg in _REG_STEERING_FIELDS:
                    vals = [r[reg] for r in _verified if r[reg] is not None]
                    if not vals:
                        continue
                    true_pct = sum(1 for v in vals if v) / len(vals)
                    if true_pct > _SKEW_THRESHOLD:
                        reg_directives_for_phase2[reg] = (
                            0, f"currently {true_pct:.0%} true — need more false"
                        )
                        print(f"    ⚠ {reg}: {true_pct:.0%} true → steering phase 2 toward false")
                    elif true_pct < (1 - _SKEW_THRESHOLD):
                        reg_directives_for_phase2[reg] = (
                            1, f"currently {true_pct:.0%} true — need more true"
                        )
                        print(f"    ⚠ {reg}: {true_pct:.0%} true → steering phase 2 toward true")

                if not reg_directives_for_phase2:
                    print("    ✓ No regulation skew detected — phase 2 unsteered")
        except Exception as _e:
            print(f"  ⚠ Regulation checkpoint failed ({_e}) — phase 2 unsteered")

    # ── Phase 2: generate remaining venues with regulation directives ─────────
    if reg_directives_for_phase2:
        for brief in phase2_briefs:
            brief["regulation_directives"] = reg_directives_for_phase2

    _run_batch(phase2_briefs)

    print()  # newline after progress bar

    if failures:
        print(f"  [x] {len(successes)} succeeded  [ ] {len(failures)} failed:")
        for f in failures:
            print(f"    [ ] {f.get('brief_name','?')}: {f.get('message', f.get('error','?'))[:80]}")
    else:
        print(f"  [x] All {len(successes)} venues generated successfully")

    # ── Step 6: Validate ─────────────────────────────────────────────────────
    print("\n[6] Validating venue pool...")
    validation = validate_city(city_key, full=False, db_path=db_path)
    print_report(validation)

    # ── Step 7: Travel matrix ─────────────────────────────────────────────────
    matrix_pairs = 0
    if not skip_matrix:
        print("\n[7] Building travel matrix...")
        from scripts.generation.build_travel_matrix import build_travel_matrix
        matrix_result = build_travel_matrix(
            city=city_key,
            api_key=ors_key,
            db_path=db_path,
            dry_run=dry_run,
        )
        matrix_pairs = matrix_result.get("pairs", 0)
        method = matrix_result.get("method", "haversine")
        status = matrix_result.get("status", "?")
        if status in ("ok", "dry_run"):
            print(f"  [x] {matrix_pairs} pairs computed via {method}")
        elif status == "no_venues":
            print("  ⚠ No venues with coordinates - matrix skipped")
        else:
            print(f"  ⚠ Matrix status: {status}")
    else:
        print("\n[7] Travel matrix skipped (--skip-matrix)")

    # ── Step 8a: Ticket availability (probabilistic baseline) ─────────────────
    # Runs BEFORE event writing so that deterministic sold_out rows from
    # write_planned_events win via INSERT OR REPLACE over probabilistic rows.
    ticket_rows = 0
    if not skip_tickets:
        print("\n[8a] Populating ticket availability...")
        from scripts.generation.populate_ticket_availability import populate_ticket_availability
        ta_result = populate_ticket_availability(
            city=city_key,
            dry_run=dry_run,
            db_path=db_path,
        )
        ticket_rows = ta_result.get("rows", 0)
        ta_status = ta_result.get("status", "?")
        if ta_status == "ok":
            print(f"  [x] {ticket_rows} availability rows written "
                  f"({ta_result.get('sold_out', 0)} sold-out, "
                  f"{ta_result.get('limited', 0)} limited)")
        elif ta_status == "no_windows":
            print("  ⚠ No windows in DB - ticket availability skipped")
        elif ta_status == "no_bookable_venues":
            print("  ⚠ No booking_required venues - ticket availability skipped")
        else:
            print(f"  ⚠ Ticket availability status: {ta_status}")
    else:
        print("\n[8a] Ticket availability skipped (--skip-tickets)")

    # ── Step 8b: Write events to DB (deterministic sold_out overrides) ────────
    # Runs AFTER ticket availability so event-specific sold_out_dates
    # (the primary mechanism for type6 difficulty) override the probabilistic
    # rows written in 8a.
    total_events_written = 0
    windows_processed    = []

    if all_events and _windows_to_process:
        print(f"\n[8b] Writing {len(all_events)} events to DB...")

        _conn2 = get_connection(db_path)
        _venue_rows = _conn2.execute(
            "SELECT venue_id, name FROM venues WHERE city = ? AND page_status = 'verified'",
            (city_key,)
        ).fetchall()
        _conn2.close()

        _name_to_id = {r["name"]: r["venue_id"] for r in _venue_rows}
        venue_id_map = {
            i: _name_to_id.get(b["name"])
            for i, b in enumerate(briefs)
            if _name_to_id.get(b["name"])
        }

        # Log dropped events (venues that failed generation)
        _dropped = sum(1 for ev in all_events if not venue_id_map.get(ev.get("venue_index")))
        if _dropped:
            print(f"  ⚠ {_dropped} event(s) dropped — venue generation failed for those venues")

        events_by_window: dict[str, list] = {}
        for ev in all_events:
            events_by_window.setdefault(ev["window_id"], []).append(ev)

        for window in _windows_to_process:
            wid = window["window_id"]
            wevents = events_by_window.get(wid, [])
            if wevents:
                n = write_planned_events(
                    event_briefs=wevents,
                    venue_id_map=venue_id_map,
                    city=city_key,
                    window_id=wid,
                    window_dates=window.get("dates", []),
                    db_path=db_path,
                )
                total_events_written += n
                windows_processed.append(wid)
    elif _windows_to_process and not dry_run:
        print("\n  No events to write (generation skipped or returned empty)")

    # ── Step 9: Venue difficulty scores ───────────────────────────────────────
    venue_difficulty_count = 0
    if not skip_venue_difficulty:
        print("\n[9] Computing venue difficulty scores...")
        from scripts.generation.compute_venue_difficulty import compute_all_venue_difficulties
        difficulty_scores = compute_all_venue_difficulties(
            city=city_key,
            dry_run=dry_run,
            db_path=db_path,
        )
        venue_difficulty_count = len(difficulty_scores)
        if difficulty_scores:
            mean_score = sum(difficulty_scores.values()) / len(difficulty_scores)
            print(f"  [x] {venue_difficulty_count} venue difficulty scores computed "
                  f"(mean={mean_score:.3f})")
        else:
            print("  ⚠ No venues scored (no verified venues or source docs)")
    else:
        print("\n[9] Venue difficulty scores skipped (--skip-venue-difficulty)")

    # ── Step 10: Venue events (events table) ─────────────────────────────────
    events_written = 0
    if not dry_run:
        print("\n[10] Writing venue events to events table...")
        try:
            from scripts.generation.generate_events import generate_events as _gen_events
            ev_result = _gen_events(city_key, dry_run=False, db_path=db_path)
            events_written = ev_result.get("total_events", 0)
            sold_out_ev = ev_result.get("sold_out", 0)
            access_ev   = ev_result.get("affects_access", 0)
            if ev_result.get("status") == "ok":
                print(f"  [x] {events_written} events written "
                      f"({sold_out_ev} sold-out, {access_ev} affects-access)")
            else:
                print(f"  ⚠ Event generation status: {ev_result.get('status')}")
        except Exception as e:
            print(f"  ⚠ Event generation failed: {e}")
    else:
        print("\n[10] Venue events skipped (dry-run)")

    # ── Step 11: Venue window flags (geographic/seasonal annotations) ─────────
    flags_written = 0
    if not dry_run:
        print("\n[11] Annotating venues with window flags...")
        try:
            from scripts.generation.annotate_venues_for_window import annotate_city
            flag_result = annotate_city(city_key, db_path=db_path)
            flags_written = flag_result.get("annotated", 0)
            if flag_result.get("status") == "ok":
                flag_counts = flag_result.get("flag_counts", {})
                active = sum(1 for v in flag_counts.values() if v > 0)
                print(f"  [x] {flags_written} venues annotated "
                      f"({active} with active flags)")
            elif flag_result.get("status") == "skipped":
                print(f"  ~ {flag_result.get('note','No annotator for this city')}")
            else:
                print(f"  ⚠ Annotation status: {flag_result.get('status')}")
        except Exception as e:
            print(f"  ⚠ Window flag annotation failed: {e}")
    else:
        print("\n[11] Window flag annotation skipped (dry-run)")

    return {
        "city":                   city,
        "total_briefs":           len(briefs),
        "succeeded":              len(successes),
        "failed":                 len(failures),
        "failures":               failures,
        "validation_passed":      validation["passed"],
        "validation_issues":      validation["issues"],
        "validation_warnings":    validation["warnings"],
        "stats":                  validation["stats"],
        "events_written":         total_events_written,
        "windows_processed":      windows_processed,
        "matrix_pairs":           matrix_pairs,
        "ticket_rows":            ticket_rows,
        "venue_difficulty_count": venue_difficulty_count,
        "venue_events_written":   events_written,
        "venue_flags_written":    flags_written,
    }


