    _db = args.db or get_city_db_path(args.city, run_name=getattr(args,'run_name',None))
    init_db(_db)
    result = generate_city_venues(
        city=args.city,
        api_key=None if args.dry_run else args.api_key,
        anthropic_key=_anthropic_key,
        model=args.model,
        planning_model=getattr(args, "planning_model", None),
        dry_run=args.dry_run,
        workers=args.workers,
        verbose=args.verbose,
        limit=args.limit,
        wrong_info_only=args.wrong_info_only,
        window_id=getattr(args, "window", None),
        db_path=_db,
    )

