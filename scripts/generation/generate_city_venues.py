def generate_city_interests(city_config: dict,
                             api_key: str = None,
                             model: str = "claude-sonnet-4-6",
                             n: int = 10) -> list[str]:
    """
    Return N city-specific visitor interest labels.
    Represents WHY people visit this city - not generic travel activities.
    Used to populate the Cat 6 interest menu in task generation prompts.

    Returns hardcoded list for Paris/London.
    Makes an LLM call for other cities if api_key is provided.
    Caches result in city_config["visitor_interests"].
    """
    city = city_config.get("city", "").lower()

    if city_config.get("visitor_interests"):
        return city_config["visitor_interests"]

    interests = _CITY_DEFAULT_INTERESTS.get(city, [])[:n]
    if interests:
        city_config["visitor_interests"] = interests
        return interests

    if not api_key:
        generic = [
            f"{city_config.get('display_name', city)} sights", "Local cuisine",
            "History", "Art & culture", "Architecture", "Parks & outdoor",
            "Shopping", "Music & nightlife", "Photography", "Local neighbourhoods",
        ][:n]
        city_config["visitor_interests"] = generic
        return generic

    try:
        from anthropic import Anthropic as _Anthropic
        client = _Anthropic(api_key=api_key)
        example = ('["Impressionist art", "Haussmann architecture", "French gastronomy", '
                   '"Wine culture", "Fashion", "History", "Canal walks", '
                   '"Photography", "Literary culture", "Contemporary galleries"]')
        prompt = (
            f"List exactly {n} broad visitor interests for {city_config['display_name']}, "
            f"{city_config['country']}. WHY tourists visit this specific city. "
            f"2-5 words each. Example for Paris: {example}. "
            f"Return {n} items for {city_config['display_name']}."
        )
        resp = client.messages.create(
            model=model, max_tokens=500,
            system="Return only a valid JSON array of strings. No markdown.",
            messages=[{"role": "user", "content": prompt}]
        )
        raw = resp.content[0].text.strip().lstrip("```json").lstrip("```").rstrip("```").strip()
        interests = json.loads(raw)
        if isinstance(interests, list) and len(interests) >= n:
            interests = interests[:n]
            city_config["visitor_interests"] = interests
            return interests
    except Exception as e:
        print(f"  ⚠ Interest generation failed ({e}), using generic fallback")

    generic = [
        f"{city_config.get('display_name', city)} sights", "Local cuisine",
        "History", "Art & culture", "Architecture", "Parks & outdoor",
        "Shopping", "Music & nightlife", "Photography", "Local neighbourhoods",
    ][:n]
    city_config["visitor_interests"] = generic
    return generic


def _generate_stub_briefs(city_config: dict, n_venues: int = 50) -> list[dict]:
    """Generate deterministic stub venue briefs from city config. Scales with n_venues."""
    districts = city_config["districts"]
    cuisines = city_config["cuisine_variety"]
    local = city_config["local_cuisine_label"]

    briefs = []

    # Scale tier pool and wrong_info count with n_venues
    _n_high = max(3, round(n_venues * 0.26))
    _n_mid  = max(5, round(n_venues * 0.42))
    _n_low  = n_venues - _n_high - _n_mid
    _n_wi   = max(2, round(n_venues * 0.40))  # W1: raised from 0.24
    tier_pool = (
        ["high"] * _n_high +
        ["mid"]  * _n_mid  +
        ["low"]  * _n_low
    )

    # Wrong info: only mid/low are candidates; take first _n_wi of them
    mid_low_indices = [i for i, t in enumerate(tier_pool) if t in ("mid", "low")]
    wrong_info_indices = set(mid_low_indices[:_n_wi])

    idx = 0
    dist_cycle = districts * max(6, n_venues // 8 + 1)  # enough to cover n_venues

    # ── Food/drink (25) ──────────────────────────────────────────────────────
    # Restaurants (10)
    cuisine_iter = iter(cuisines * 3)
    for i in range(10):
        cuisine = next(cuisine_iter) if i >= 2 else local
        briefs.append({
            "name": f"Stub Restaurant {i+1} ({cuisine.title()})",
            "category": "restaurant",
            "district": dist_cycle[idx % len(dist_cycle)],
            "traffic_tier": tier_pool[idx],
            "has_wrong_info": idx in wrong_info_indices,
            "character": (f"A {cuisine} restaurant in {dist_cycle[idx % len(dist_cycle)]} "
                          f"serving traditional dishes in a "
                          f"{'cozy' if i % 2 == 0 else 'lively'} setting.")
        })
        idx += 1

    # Cafes (10 - up from 5 to balance 25)
    for i in range(10):
        briefs.append({
            "name": f"Stub Cafe {i+1}",
            "category": "cafe",
            "district": dist_cycle[idx % len(dist_cycle)],
            "traffic_tier": tier_pool[idx],
            "has_wrong_info": idx in wrong_info_indices,
            "character": (f"An independent cafe in {dist_cycle[idx % len(dist_cycle)]} "
                          f"with good coffee and a quiet atmosphere.")
        })
        idx += 1

    # Bars (5)
    for i in range(5):
        briefs.append({
            "name": f"Stub Bar {i+1}",
            "category": "bar",
            "district": dist_cycle[idx % len(dist_cycle)],
            "traffic_tier": tier_pool[idx],
            "has_wrong_info": idx in wrong_info_indices,
            "character": (f"A cocktail bar in {dist_cycle[idx % len(dist_cycle)]} "
                          f"with a late-night crowd and creative drinks menu.")
        })
        idx += 1

    # ── Sights/attractions (25) ──────────────────────────────────────────────
    # Museums (7)
    for i in range(7):
        briefs.append({
            "name": f"Stub Museum {i+1}",
            "category": "museum",
            "district": dist_cycle[idx % len(dist_cycle)],
            "traffic_tier": tier_pool[idx],
            "has_wrong_info": idx in wrong_info_indices,
            "character": (f"A museum in {dist_cycle[idx % len(dist_cycle)]} "
                          f"with rotating exhibitions and a permanent collection.")
        })
        idx += 1

    # Attractions (10 - up from 6)
    for i in range(10):
        briefs.append({
            "name": f"Stub Attraction {i+1}",
            "category": "attraction",
            "district": dist_cycle[idx % len(dist_cycle)],
            "traffic_tier": tier_pool[idx],
            "has_wrong_info": idx in wrong_info_indices,
            "character": (f"A popular attraction in {dist_cycle[idx % len(dist_cycle)]} "
                          f"visited by locals and tourists alike.")
        })
        idx += 1

    # Parks (5 - up from 4)
    for i in range(5):
        briefs.append({
            "name": f"Stub Park {i+1}",
            "category": "park",
            "district": dist_cycle[idx % len(dist_cycle)],
            "traffic_tier": tier_pool[idx],
            "has_wrong_info": False,  # parks rarely have wrong info
            "character": (f"A public park in {dist_cycle[idx % len(dist_cycle)]} "
                          f"popular for walks and picnics.")
        })
        idx += 1

    # Neighbourhood (3)
    for i in range(3):
        briefs.append({
            "name": f"Stub Neighbourhood Walk {i+1}",
            "category": "neighbourhood",
            "district": dist_cycle[idx % len(dist_cycle)],
            "traffic_tier": "low",
            "has_wrong_info": False,
            "character": (f"A self-guided neighbourhood walk through "
                          f"{dist_cycle[idx % len(dist_cycle)]} with independent shops and cafes.")
        })
        idx += 1

    assert len(briefs) == 50, f"Stub generator produced {len(briefs)} briefs, expected 50"
    return briefs


# ─────────────────────────────────────────────────────────────────────────────
# DEDUP BRIEFS
# ─────────────────────────────────────────────────────────────────────────────

def _dedup_briefs(briefs: list[dict]) -> list[dict]:
    """
    Remove near-duplicate venue briefs from the plan_venues output.

    Two briefs are considered duplicates when ALL three conditions hold:
      1. Jaccard similarity of word tokens >= 0.75
      2. Same category
      3. Same district

    The longer (more complete) name is kept; the shorter is dropped.
    Operates in O(n²) but n is always ≤ ~100 so this is negligible.
    """
    import re as _re

    def _norm(name: str) -> set:
        # Strip apostrophes and hyphens first (they join parts of a word, not separate them)
        # then replace remaining punctuation with spaces for tokenisation
        s = _re.sub(r"['\-]", "", name.lower())
        s = _re.sub(r"[^\w\s]", " ", s)
        return set(s.split())

    to_remove: set[int] = set()

    for i, ba in enumerate(briefs):
        if i in to_remove:
            continue
        for j in range(i + 1, len(briefs)):
            if j in to_remove:
                continue
            bb = briefs[j]
            if ba.get("category") != bb.get("category"):
                continue
            if ba.get("district") != bb.get("district"):
                continue
            ta, tb = _norm(ba["name"]), _norm(bb["name"])
            if not ta or not tb:
                continue
            jaccard = len(ta & tb) / len(ta | tb)
            if jaccard >= 0.75:
                # Keep the longer name (more descriptive); drop the shorter
                keep, drop = (i, j) if len(ba["name"]) >= len(bb["name"]) else (j, i)
                to_remove.add(drop)
                print(f"  [dedup] Removed '{briefs[drop]['name']}' "
                      f"(duplicate of '{briefs[keep]['name']}', "
                      f"score={jaccard:.2f}, "
                      f"cat={ba['category']}, dist={ba['district']})")

    if to_remove:
        cleaned = [b for i, b in enumerate(briefs) if i not in to_remove]
        print(f"  [dedup] {len(to_remove)} duplicate(s) removed "
              f"({len(briefs)} → {len(cleaned)} briefs)")
        return cleaned
    return briefs


