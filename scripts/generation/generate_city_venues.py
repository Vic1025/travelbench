def plan_venues(city_config: dict, window: dict = None,
                api_key: str = None,
                model: str = "claude-sonnet-4-6",
                dry_run: bool = False,
                n_venues: int = 50) -> tuple[list[dict], list[dict]]:
    """
    Generate 50 venue briefs (and 5-8 event briefs if a window is provided).

    When window is given: calls _plan_prompt_with_events() - one LLM call
    returns both venues and events together, so events are semantically
    coherent with the venue pool from the start.

    Returns:
        (venue_briefs, event_briefs)
        venue_briefs: list of 50 venue dicts
        event_briefs: list of event dicts (empty if no window)
            Each event has venue_index (into venue_briefs), to be resolved
            to venue_id after the venues are written to DB.
    """
    if dry_run or not api_key:
        print("  Using stub venue plan (no API call)")
        return _generate_stub_briefs(city_config, n_venues=n_venues), []

    print("  Planning venue mix with LLM (real-venue-first)...")
    try:
        from anthropic import Anthropic as _Anthropic
    except ImportError:
        raise ImportError("anthropic package required: pip install anthropic")

    client = _Anthropic(api_key=api_key)
    # Events are generated separately at step 4 (generate_events_for_windows).
    # Window is still passed for seasonal context in the venue prompt, but
    # include_events=False avoids generating events that would be discarded.
    prompt = _plan_prompt_with_events(city_config, window=window, include_events=False, n_venues=n_venues)

    def _call_once(max_tok):
        resp = client.messages.create(
            model=model,
            max_tokens=max_tok,
            system="You are a helpful data generation assistant. Return only valid complete JSON, no truncation.",
            messages=[{"role": "user", "content": prompt}]
        )
        r = resp.content[0].text.strip()
        r = re.sub(r'```(?:json)?\s*', '', r)
        r = re.sub(r'```', '', r).strip()
        return r

    raw = ""
    for max_tok in [12000, 16000, 20000, 24000]:
        raw = _call_once(max_tok)
        if not raw:
            continue
        try:
            parsed = json.loads(raw)
            break
        except json.JSONDecodeError as e:
            print(f"  ⚠ JSON parse failed at {max_tok} tokens ({e}) - retrying...")
            continue
    else:
        raise ValueError(f"Could not get valid JSON from LLM. Last output:\n{raw[:500]}")

    # Extract venues from response (events generated separately at step 4)
    if isinstance(parsed, dict) and "venues" in parsed:
        briefs = parsed.get("venues", [])
    elif isinstance(parsed, list):
        briefs = parsed
    else:
        briefs = []
    event_briefs = []  # events handled by generate_events_for_windows

    # Deduplicate briefs before count validation
    briefs = _dedup_briefs(briefs)

    # Validate + normalise venue count
    if len(briefs) != n_venues:
        print(f"  ⚠ LLM returned {len(briefs)} briefs (expected {n_venues}) - padding/trimming")
        if len(briefs) > n_venues:
            # Tier-aware selection: keep ALL high-traffic venues (iconic landmarks
            # are always worth including), then fill mid/low at their FULL quotas.
            # Total may exceed n_venues — that's intentional.
            high_briefs = [b for b in briefs if b.get("traffic_tier") == "high"]
            non_high    = [b for b in briefs if b.get("traffic_tier") != "high"]

            # Mid/low get their original quotas (not squeezed by extra highs)
            _n_mid_t    = max(5, round(n_venues * 0.42))
            _n_low_t    = n_venues - max(3, round(n_venues * 0.26)) - _n_mid_t

            kept = list(high_briefs)
            tier_counts = {"mid": 0, "low": 0}
            tier_caps   = {"mid": _n_mid_t, "low": _n_low_t}
            overflow    = []

            for b in non_high:
                t = b.get("traffic_tier", "mid")
                if tier_counts.get(t, 0) < tier_caps.get(t, 0):
                    kept.append(b)
                    tier_counts[t] = tier_counts.get(t, 0) + 1
                else:
                    overflow.append(b)

            # If any tier under-produced, fill from overflow
            for tier in ["mid", "low"]:
                shortfall = tier_caps[tier] - tier_counts[tier]
                if shortfall > 0:
                    tier_overflow = [b for b in overflow if b.get("traffic_tier") == tier]
                    kept.extend(tier_overflow[:shortfall])
                    overflow = [b for b in overflow if b not in tier_overflow[:shortfall]]

            briefs = kept
            print(f"  Tier-aware selection: {len(high_briefs)} high (all kept) + "
                  f"{tier_counts['mid']} mid + {tier_counts['low']} low = {len(briefs)} total")
        else:
            stub_extras = _generate_stub_briefs(city_config, n_venues=n_venues)[len(briefs):]
            briefs += stub_extras[:n_venues - len(briefs)]

    # Enforce food/sight pool balance scaled to n_venues
    FOOD_CATS  = {"restaurant", "cafe", "bar"}
    SIGHT_CATS = {"museum", "attraction", "park", "neighbourhood"}
    food   = [b for b in briefs if b["category"] in FOOD_CATS]
    sights = [b for b in briefs if b["category"] in SIGHT_CATS]
    _n_food   = n_venues // 2
    _n_sights = n_venues - _n_food

    if len(food) != _n_food or len(sights) != _n_sights:
        print(f"  ⚠ Pool imbalance: {len(food)} food / {len(sights)} sights - rebalancing")
        while len(food) > _n_food:
            b = food.pop(); b["category"] = "attraction"; sights.append(b)
        while len(sights) > _n_sights:
            b = sights.pop(); b["category"] = "restaurant"; food.append(b)
        briefs = food + sights

    # Validate event_briefs - remove any with out-of-range venue_index
    valid_events = []
    for ev in event_briefs:
        idx = ev.get("venue_index")
        if isinstance(idx, int) and 0 <= idx < len(briefs):
            valid_events.append(ev)
        else:
            print(f"  ⚠ Event '{ev.get('name','?')}' has invalid venue_index {idx} - skipped")
    event_briefs = valid_events

    print(f"  [x] Venue plan ready: {len(briefs)} briefs ({len(event_briefs)} events planned)")
    return briefs, event_briefs





def write_planned_events(event_briefs: list[dict],
                          venue_id_map: dict[int, str],
                          city: str,
                          window_id: str,
                          window_dates: list[str],
                          db_path=None) -> int:
    """
    Write event briefs to the events table after venues have been saved to DB.

    venue_id_map: {venue_index: venue_id} - built after venue DB writes complete.
    Also writes sold_out_dates into ticket_availability for per-date sold-out traps.

    Returns number of events written.
    """
    from scripts.generation.db import get_connection, get_city_db_path
    conn = get_connection(db_path or get_city_db_path(city))
    written = 0

    for ev in event_briefs:
        idx    = ev.get("venue_index")
        vid    = venue_id_map.get(idx)
        if not vid:
            continue

        # Write event row
        try:
            conn.execute("""
                INSERT INTO events
                  (venue_id, city, window_id, name, description,
                   start_date, end_date, affects_hours, affects_access,
                   sold_out, modified_hours, price_local)
                VALUES (?,?,?,?,?,?,?,?,?,?,?,?)
            """, (
                vid, city, window_id,
                ev.get("name", "Special Event"),
                ev.get("description", ""),
                ev.get("start_date", window_dates[0] if window_dates else ""),
                ev.get("end_date",   window_dates[-1] if window_dates else ""),
                1 if ev.get("affects_hours") else 0,
                1 if ev.get("affects_access") else 0,
                1 if ev.get("sold_out") else 0,
                ev.get("modified_hours"),
                ev.get("price_local"),
            ))
            written += 1
        except Exception as e:
            print(f"  ⚠ Failed to write event '{ev.get('name')}': {e}")
            continue

        # Write sold_out_dates into ticket_availability
        for date_str in ev.get("sold_out_dates", []):
            if date_str not in window_dates:
                continue
            try:
                conn.execute("""
                    INSERT OR REPLACE INTO ticket_availability
                      (venue_id, date, status, sold_out, notes)
                    VALUES (?, ?, 'sold_out', 1, ?)
                """, (vid, date_str, f"Sold out - {ev.get('name', 'event')}"))
            except Exception:
                pass

    conn.commit()
    conn.close()
    print(f"  [x] {written}/{len(event_briefs)} events written to DB")
    return written



