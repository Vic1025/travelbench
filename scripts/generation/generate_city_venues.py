def _build_venue_list_for_events(briefs: list[dict]) -> tuple[str, list[int]]:
    """Format venue pool for the event generation prompt. Returns (text, high_traffic_indices)."""
    lines = []
    high_indices = []
    for i, b in enumerate(briefs):
        tier = b.get("traffic_tier", "mid")
        if tier == "high":
            high_indices.append(i)
        lines.append(
            f"  [{i:2d}] {b['name']} ({b['category']}, {b['district']}, {tier})"
            f" - {b.get('character', '')}"
        )
    return "\n".join(lines), high_indices


def _build_window_list_for_events(windows: list[dict]) -> str:
    """Format windows for the event generation prompt."""
    lines = []
    for w in windows:
        anchor_str = ", ".join(
            f"{e['name']} ({e['date']})" for e in w.get("anchor_events", [])
        )
        lines.append(
            f"  {w['window_id']}: {w['label']}  |  "
            f"{w['dates'][0]}–{w['dates'][-1]}  |  "
            f"Anchors: {anchor_str}"
        )
    return "\n".join(lines)


def _validate_events(events: list, windows: list[dict],
                     n_venues: int, high_indices: list[int]) -> list[str]:
    """Validate event list against all E1 constraints. Returns error strings (empty = ok)."""
    errors = []
    window_map = {w["window_id"]: w for w in windows}
    all_dates_by_window = {w["window_id"]: set(w["dates"]) for w in windows}

    events_by_window: dict[str, list] = {w["window_id"]: [] for w in windows}
    venue_event_count: dict[int, int] = {}

    for i, ev in enumerate(events):
        wid = ev.get("window_id", "")
        vidx = ev.get("venue_index")

        if wid not in window_map:
            errors.append(f"event[{i}] '{ev.get('name')}': unknown window_id '{wid}'")
            continue
        if not isinstance(vidx, int) or not (0 <= vidx < n_venues):
            errors.append(f"event[{i}] '{ev.get('name')}': venue_index {vidx} out of range [0,{n_venues})")
            continue

        events_by_window[wid].append(ev)
        venue_event_count[vidx] = venue_event_count.get(vidx, 0) + 1

        # Dates within window
        window_dates = all_dates_by_window[wid]
        for d in [ev.get("start_date"), ev.get("end_date")]:
            if d and d not in window_dates:
                errors.append(f"event[{i}] '{ev.get('name')}': date {d} outside window {wid}")
        for d in ev.get("sold_out_dates", []):
            if d not in window_dates:
                errors.append(f"event[{i}] '{ev.get('name')}': sold_out_date {d} outside window {wid}")

        # No sold_out / affects_access on high-traffic venues
        if vidx in high_indices:
            if ev.get("sold_out") or ev.get("sold_out_dates"):
                errors.append(f"event[{i}]: sold_out on high-traffic venue [{vidx}]")
            if ev.get("affects_access"):
                errors.append(f"event[{i}]: affects_access on high-traffic venue [{vidx}]")

    # Per-window checks
    for wid, wevents in events_by_window.items():
        w = window_map[wid]
        anchor_dates = {e["date"] for e in w.get("anchor_events", [])}

        if not (4 <= len(wevents) <= 8):
            errors.append(f"window {wid}: need 4-8 events, got {len(wevents)}")
        if not any(ev.get("affects_access") for ev in wevents):
            errors.append(f"window {wid}: need >=1 affects_access event")
        if not any(ev.get("affects_hours") for ev in wevents):
            errors.append(f"window {wid}: need >=1 affects_hours event")

        has_anchor_soldout = any(
            d in anchor_dates
            for ev in wevents
            for d in ev.get("sold_out_dates", [])
        )
        if not has_anchor_soldout:
            errors.append(f"window {wid}: need >=1 sold_out_date on an anchor date")

        cats_in_window = {
            ev.get("_category", "") for ev in wevents if ev.get("_category")
        }
        if cats_in_window and len(cats_in_window) < 3:
            errors.append(
                f"window {wid}: events span only {len(cats_in_window)} categories (need >=3)"
            )

    # Per-venue max 2 events
    for vidx, count in venue_event_count.items():
        if count > 2:
            errors.append(f"venue[{vidx}]: has {count} events across all windows (max 2)")

    return errors


def generate_events_for_windows(city_config: dict,
                                  windows: list[dict],
                                  venue_briefs: list[dict],
                                  city_interests: list[str],
                                  api_key: str,
                                  model: str = "claude-sonnet-4-6") -> list[dict]:
    """
    Generate events for ALL windows in a single LLM call.

    Runs AFTER venue briefs are confirmed (post-enrich), so events are assigned
    to real venues with known categories. This is separate from plan_venues -
    the plan_venues path still produces events-as-side-effect for the first window
    only, but this function is the canonical Step 4 for the full pipeline.

    Returns a flat list of event dicts, each with venue_index and window_id.
    The orchestrator converts this to events_by_venue: dict[int, list[dict]]
    before passing to _generate_one.

    On LLM failure returns [] - events are additive, pipeline continues.
    """
    if not api_key or not windows or not venue_briefs:
        return []

    venue_list, high_indices = _build_venue_list_for_events(venue_briefs)
    window_list = _build_window_list_for_events(windows)
    interests_str = ", ".join(city_interests[:10]) if city_interests else "general tourism"

    prompt = _EVENT_GEN_PROMPT.format(
        display_name=city_config.get("display_name", ""),
        country=city_config.get("country", ""),
        n_venues=len(venue_briefs),
        venue_list=venue_list,
        n_windows=len(windows),
        window_list=window_list,
        interests=interests_str,
        high_traffic_indices=high_indices,
    )

    try:
        from anthropic import Anthropic as _Anthropic
    except ImportError:
        print("  ⚠ anthropic package not available - skipping event generation")
        return []

    client = _Anthropic(api_key=api_key)
    events = None
    last_error = ""

    for attempt in range(3):
        try:
            resp = client.messages.create(
                model=model,
                max_tokens=6000,
                system="Return only a valid JSON array. No markdown, no explanation.",
                messages=[{"role": "user", "content": prompt}]
            )
            raw = resp.content[0].text.strip()
            raw = re.sub(r'```(?:json)?\s*', '', raw)
            raw = re.sub(r'```', '', raw).strip()
            candidate = json.loads(raw)
            if not isinstance(candidate, list):
                raise ValueError("expected JSON array")

            # Inject _category for validation
            for ev in candidate:
                vidx = ev.get("venue_index")
                if isinstance(vidx, int) and 0 <= vidx < len(venue_briefs):
                    ev["_category"] = venue_briefs[vidx].get("category", "")

            errs = _validate_events(candidate, windows, len(venue_briefs), high_indices)
            if errs:
                last_error = f"validation: {errs[:3]}"
                print(f"  ⚠ Event gen attempt {attempt+1} validation errors: {errs[:3]}")
                # Auto-fix: drop events with structural errors (bad window / out-of-range index)
                known_wids = {w["window_id"] for w in windows}
                candidate = [
                    ev for ev in candidate
                    if ev.get("window_id") in known_wids
                    and isinstance(ev.get("venue_index"), int)
                    and 0 <= ev["venue_index"] < len(venue_briefs)
                ]
                errs2 = _validate_events(candidate, windows, len(venue_briefs), high_indices)
                if not errs2:
                    events = candidate
                    break
                last_error = f"post-fix: {errs2[:3]}"
            else:
                events = candidate
                break
        except Exception as e:
            last_error = str(e)
            print(f"  ⚠ Event gen attempt {attempt+1} error: {e}")

    if events is None:
        print(f"  ⚠ Event generation failed ({last_error}) - continuing without events")
        return []

    # Remove internal _category field before returning
    for ev in events:
        ev.pop("_category", None)

    by_window = {}
    for ev in events:
        by_window.setdefault(ev["window_id"], []).append(ev)
    summary = ", ".join(f"{wid}: {len(evs)}" for wid, evs in by_window.items())
    print(f"  [x] {len(events)} events generated ({summary})")
    return events

def build_event_prompt_block(event_briefs: list[dict],
                              venue_briefs: list[dict],
                              window_dates: list[str]) -> str:
    """
    Build the ACTIVE EVENTS block injected into the task generation prompt.
    Called after plan_venues() returns event_briefs, before venue DB writes
    (venue_index still valid at this point).

    Returns a formatted string ready to inject into build_typed_task_prompt.
    """
    if not event_briefs:
        return ""

    lines = ["ACTIVE EVENTS DURING THIS WINDOW:"]
    lines.append("These events are confirmed - task generation agents should know about them.")
    lines.append("Build Type 6, Type 5, or Type 2 tasks that interact with these events.")
    lines.append("")

    for ev in event_briefs:
        idx   = ev.get("venue_index", "?")
        vname = venue_briefs[idx]["name"] if isinstance(idx, int) and idx < len(venue_briefs) else "?"
        vcat  = venue_briefs[idx]["category"] if isinstance(idx, int) and idx < len(venue_briefs) else "?"

        sold_dates = ev.get("sold_out_dates", [])
        access_str = "booking required" if ev.get("affects_access") else "walk-in"
        hours_str  = f"Hours: {ev['modified_hours']}" if ev.get("modified_hours") else ""
        sold_str   = f"SOLD OUT on: {', '.join(sold_dates)}" if sold_dates else ""
        price_str  = f"Price: ${ev['price_local']:.0f}" if ev.get("price_local") else "free"

        details = " | ".join(filter(None, [hours_str, price_str, access_str, sold_str]))

        lines.append(f"  [{idx}] {vname} ({vcat}) - {ev.get('name', '?')}")
        lines.append(f"      {ev.get('start_date','')} to {ev.get('end_date','')}")
        lines.append(f"      {details}")
        lines.append(f"      {ev.get('description', '')}")
        lines.append(f"      Best for: {ev.get('task_hook', 'general')}")
        lines.append("")

    return "\n".join(lines)


